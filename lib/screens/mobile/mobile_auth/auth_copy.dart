String authText(BuildContext context, String key) {
  final language = Localizations.localeOf(context).languageCode;
  return _translations[language]?[key] ?? _en[key] ?? key;
}

String authErrorText(BuildContext context, String code) {
  switch (code) {
    case 'invalid-credential':
    case 'wrong-password':
    case 'user-not-found':
      return authText(context, 'invalidLogin');
    case 'email-already-in-use':
      return authText(context, 'emailInUse');
    case 'weak-password':
      return authText(context, 'weakPassword');
    case 'invalid-email':
      return authText(context, 'invalidEmail');
    case 'too-many-requests':
      return authText(context, 'tooManyRequests');
    case 'network-request-failed':
      return authText(context, 'networkError');
    default:
      return authText(context, 'genericAuthError');
  }
}
